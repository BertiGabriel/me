function NewsletterSection() {
    const [email, setEmail] = React.useState('');
    const [status, setStatus] = React.useState('idle');
    const [error, setError] = React.useState('');

    const handleSubmit = async (e) => {
        e.preventDefault();
        
        if (!email) {
            setError('Por favor, insira seu e-mail');
            return;
        }
        
        if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
            setError('Por favor, insira um e-mail válido');
            return;
        }

        setStatus('loading');
        setError('');

        try {
            const response = await fetch('https://formspree.io/f/xwpkvgpn', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                },
                body: JSON.stringify({ email }),
            });

            if (response.ok) {
                setStatus('success');
                setEmail('');
            } else {
                throw new Error('Failed to submit');
            }
        } catch (err) {
            setStatus('error');
            setError('Algo deu errado. Por favor, tente novamente.');
        }
    };

    return (
        <section id="newsletter" className="mx-auto mt-24 max-w-6xl rounded-[32px] border p-10">
            <div className="grid gap-8 lg:grid-cols-[1.1fr_0.9fr] lg:items-center">
                <div className="space-y-4">
                    <p className="text-sm font-semibold uppercase tracking-[0.3em]">Vamos conversar</p>
                    <h2 className="text-4xl font-semibold">Interessado em colaboração ou oportunidades?</h2>
                    <p className="max-w-2xl">
                        Entre em contato para discutir projetos de produto, liderança ou empreendedorismo.
                    </p>
                </div>
                <form onSubmit={handleSubmit} className="grid gap-4">
                    <div className="flex flex-col gap-2 sm:flex-row">
                        <input 
                            type="email" 
                            placeholder="Seu melhor e-mail" 
                            value={email}
                            onChange={(e) => setEmail(e.target.value)}
                            disabled={status === 'loading'}
                            className="w-full rounded-2xl border border-slate-200 bg-white px-5 py-4 text-slate-900 outline-none transition focus:border-sky-400 dark:bg-slate-800 dark:border-slate-700 dark:text-white disabled:opacity-50" 
                            aria-label="Endereço de e-mail"
                        />
                        <button 
                            type="submit" 
                            disabled={status === 'loading'}
                            className="inline-flex items-center justify-center rounded-2xl border px-6 py-4 text-sm font-semibold transition hover:bg-black/5 dark:hover:bg-white/10 disabled:opacity-50"
                        >
                            {status === 'loading' ? 'Enviando...' : 'Enviar mensagem'}
                        </button>
                    </div>
                    {error && <p className="text-sm text-red-500" role="alert">{error}</p>}
                    {status === 'success' && <p className="text-sm text-green-500" role="status">Mensagem enviada com sucesso!</p>}
                </form>
            </div>
        </section>
    );
}

